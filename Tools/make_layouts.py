#!/usr/bin/env python3
"""Writes kind-less Tile Match layouts (Assets/Games/TileMatch/Content/Layouts/*.txt) from shape recipes.

Each layer is a set of (x, y) half-unit cells; a mark per cell ('x', 'f', 'F', 'h', 's', digits).
Re-run after changing recipes; hand-authored layouts live next to the generated ones (prefix H).
"""
import os, random, sys

OUT = os.path.join(os.path.dirname(__file__), "..", "Assets", "Games", "TileMatch", "Content", "Layouts")


def grid(cols, rows, x0=0, y0=0, step=2):
    return {(x0 + c * step, y0 + r * step) for c in range(cols) for r in range(rows)}


def diamond(radius, cx, cy):
    cells = set()
    for r in range(-radius, radius + 1):
        for c in range(-radius, radius + 1):
            if abs(r) + abs(c) <= radius:
                cells.add((cx + c * 2, cy + r * 2))
    return cells


def ring(cols, rows, x0=0, y0=0):
    return {(x, y) for (x, y) in grid(cols, rows, x0, y0) if x in (x0, x0 + (cols - 1) * 2) or y in (y0, y0 + (rows - 1) * 2)}


def render(layers, marks=None, header=()):
    marks = marks or {}
    lines = list(header)
    for index, cells in enumerate(layers):
        if not cells:
            continue
        ys = sorted({y for _, y in cells})
        dy = ys[0] % 2
        lines.append(f"layer {index}:" + (f" dy={dy}" if dy else ""))
        for y in range(dy, ys[-1] + 1, 2):
            row = [x for x, yy in cells if yy == y]
            width = max(x for x, _ in cells) + 1
            chars = [" "] * width
            for x in row:
                chars[x] = marks.get((index, x, y), "x")
            lines.append("".join(chars).rstrip() or ".")
    return "\n".join(lines) + "\n"


def count(layers):
    return sum(len(c) for c in layers)


def pyramid(base_cols, base_rows, height):
    layers = []
    for h in range(height):
        cols, rows = base_cols - h, base_rows - h
        if cols <= 0 or rows <= 0:
            break
        layers.append(grid(cols, rows, h, h))
    return layers


def trim_to_triples(layers):
    total = count(layers)
    while total % 3:
        top = max(i for i, c in enumerate(layers) if c)
        layers[top].remove(max(layers[top]))
        total -= 1
    return layers


def normalize(layers):
    """Shift every layer by the same even offset so all coordinates are ≥ 0 (parity decides overlaps)."""
    cells = [c for layer in layers for c in layer]
    mx = min(x for x, _ in cells)
    my = min(y for _, y in cells)
    sx, sy = mx - (mx % 2), my - (my % 2)
    return [{(x - sx, y - sy) for (x, y) in layer} for layer in layers]


def write(name, layers, kinds, band, marks, extra=()):
    total = count(layers)
    spawners = sum(1 for m in marks.values() if m == "s")
    assert total % 3 == 0, f"{name}: {total} tiles"
    header = [f"# generated by Tools/make_layouts.py ({total} board tiles)", "tray 7", f"kinds {kinds}", f"band {band}"]
    if spawners:
        header.append("spawner 3")
    header.extend(extra)
    with open(os.path.join(OUT, f"{name}.txt"), "w") as f:
        f.write(render(layers, marks, header=header))
    print(f"{name}: {total + spawners * 3} tiles, {len(layers)} layers, kinds {kinds}, {band}, marks {sorted(set(marks.values()))}")


RECIPES = [
    # name, kinds, band, layers, header extras, marks function
    ("L001", 3, "easy", lambda: [grid(3, 3, 0, 0)]),
    ("L002", 4, "easy", lambda: [grid(4, 3), grid(3, 2, 1, 1)]),
    ("L003", 5, "easy", lambda: pyramid(4, 4, 4)),
    ("L004", 6, "normal", lambda: trim_to_triples([grid(6, 4), grid(5, 3, 1, 1), grid(4, 2, 2, 2)])),
    ("L005", 7, "normal", lambda: trim_to_triples([diamond(3, 6, 6), {(x + 1, y + 1) for x, y in diamond(2, 6, 6)}, diamond(1, 6, 6)])),
    ("L006", 8, "hard", lambda: trim_to_triples(pyramid(6, 5, 4))),
    ("L007", 5, "easy", lambda: trim_to_triples([ring(6, 6), grid(4, 4, 2, 2), grid(2, 2, 4, 4)])),
    ("L008", 8, "normal", lambda: trim_to_triples([grid(7, 5), grid(6, 4, 1, 1), ring(5, 3, 2, 2)])),
    ("L009", 7, "normal", lambda: trim_to_triples(pyramid(5, 5, 4) + [grid(2, 1, 3, 3)])),
    ("L010", 10, "hard", lambda: trim_to_triples([grid(7, 6), grid(6, 5, 1, 1), grid(5, 4, 2, 2), ring(4, 3, 3, 3)])),
    ("L011", 9, "normal", lambda: trim_to_triples([diamond(4, 8, 8), {(x + 1, y + 1) for x, y in diamond(3, 8, 8)}, diamond(2, 8, 8)])),
    ("L012", 10, "hard", lambda: trim_to_triples(pyramid(7, 6, 5))),
]

MODIFIERS = {
    # Frozen tiles in the base layer of L009 and L010; hidden tiles under the top of L011.
    "L009": lambda layers: {(0, x, y): "f" for (x, y) in sorted(layers[0])[:3]},
    "L010": lambda layers: {(0, x, y): ("F" if i == 0 else "f") for i, (x, y) in enumerate(sorted(layers[0])[-4:])},
    "L011": lambda layers: {(1, x, y): "h" for (x, y) in sorted(layers[1])[2:6]},
}




# --- Levels 11-100: mirrored shapes on the shared difficulty curve -------------------------------------------------------
#
# Bands follow LevelCurve (Assets/Tileworks/Tiles/Runtime/Generation/LevelCurve.cs): hard 5th and 10th in every ten,
# an easy level after each, super hard at 40, 60, 80 and 100. Tile count, kinds and layers grow with the level, with hard
# levels bigger and easy ones smaller. Every layout and modifier is mirrored left to right.

OPENING_BANDS = ["easy", "easy", "easy", "easy", "normal", "easy", "normal", "normal", "normal", "hard"]

# Levels 1-12 keep the hand recipes, in curve order; L012's pyramid becomes level 15's hard level.
HAND_ORDER = {1: "L001", 2: "L002", 3: "L003", 4: "L007", 5: "L004", 6: "L005", 7: "L009", 8: "L008", 9: "L011", 10: "L010",
              12: "L006", 15: "L012"}

LINKED_FROM, SPAWNER_FROM = 14, 18


def band_at(number):
    if number <= 10:
        return OPENING_BANDS[number - 1]
    position = (number - 1) % 10 + 1
    if position in (1, 6):
        return "easy"
    if position == 5:
        return "hard"
    if position == 10:
        return "superHard" if number >= 40 and number % 20 == 0 else "hard"
    return "normal"


def tile_shape(name, cols, rows):
    """Base layer cells (half units) for a named shape, mirrored left to right."""
    cells = set()
    for r in range(rows):
        for c in range(cols):
            edge, centre = min(c, cols - 1 - c), abs(2 * c - (cols - 1))
            top, bottom, middle = r, rows - 1 - r, abs(2 * r - (rows - 1))
            keep = {
                "rect": True,
                "diamond": centre + middle <= max(cols, rows),
                "octagon": edge + min(top, bottom) >= 1,
                "heart": not (top == 0 and (edge == 0 or centre <= 1)) and edge >= 2 - bottom,
                "hourglass": not (middle <= 1 and edge == 0) and not (middle == 0 and edge == 1 and cols > 5),
                "cross": centre <= cols // 3 or middle <= rows // 3,
                "ring": edge == 0 or top == 0 or bottom == 0 or (edge >= 2 and min(top, bottom) >= 2),
                "x": abs(centre * rows - middle * cols) <= max(cols, rows) + 1,
                "arch": not (centre <= 1 and bottom <= 1),
                "towers": edge <= 1 or top <= 1,
                "butterfly": not (centre <= 1 and middle >= rows - 2) and not (edge == 0 and middle == 0),
                "crown": not (top == 0 and edge % 2 == 1),
                "tree": centre <= top + 1 and bottom >= 2 or centre <= 1,
                "chevron": abs(top - centre // 2) <= 1 or abs(top - centre // 2 - 2) <= 0,
            }[name]
            if keep:
                cells.add((2 * c, 2 * r))
    return cells


SHAPES = ["rect", "diamond", "octagon", "heart", "hourglass", "cross", "ring", "x", "arch", "towers", "butterfly", "crown", "tree",
          "chevron"]


def stack_layers(base, count, style, rng):
    """Upper layers: 'pyramid' shifts each layer half a tile, sitting on four tiles; 'stack' piles tiles straight up."""
    width = max(x for x, _ in base)
    layers, current = [base], base
    for layer in range(1, count):
        if style == "pyramid" or layer % 2 == 1 and style == "brick":
            nxt = {(x + 1, y + 1) for (x, y) in current if {(x + 2, y), (x, y + 2), (x + 2, y + 2)} <= current}
        elif style == "brick":
            nxt = {(x - 1, y - 1) for (x, y) in current if {(x - 2, y), (x, y - 2), (x - 2, y - 2)} <= current}
        else:
            xs = sorted({x for x, _ in current})
            nxt = {(x, y) for (x, y) in current if xs[0] < x < xs[-1]} if len(xs) > 2 else set()
        if layer >= 2 and nxt:
            mode = rng.choice(["all", "all", "all", "checker", "ring"])
            if mode == "checker":
                nxt = {(x, y) for (x, y) in nxt if (min(x, width - x) // 2 + y // 2) % 2 == 0}
            elif mode == "ring" and len(nxt) > 12:
                xs, ys = [x for x, _ in nxt], [y for _, y in nxt]
                nxt = {(x, y) for (x, y) in nxt if x in (min(xs), max(xs)) or y in (min(ys), max(ys))}
        if len(nxt) < 3:
            break
        layers.append(nxt)
        current = nxt
    return layers


def trim_mirrored(layers):
    """Takes tiles off the top layer, a mirrored pair or a middle tile at a time, until the total is a multiple of three."""
    width = max(x for layer in layers for x, _ in layer)
    while count(layers) % 3:
        top = max(i for i, c in enumerate(layers) if c)
        cells = sorted(layers[top], key=lambda c: (-c[1], abs(2 * c[0] - width)))
        middle = [c for c in cells if 2 * c[0] == width]
        pair = next((c for c in cells if 2 * c[0] != width), None)
        if middle and (count(layers) % 3 == 1 or pair is None):
            layers[top].discard(middle[0])
        elif pair is not None:
            layers[top].discard(pair)
            layers[top].discard((width - pair[0], pair[1]))
        else:
            layers[top].clear()
        if not layers[top]:
            layers.pop(top)
    return layers


def fit(shape, target, depth, style, rng):
    """The board size whose layout comes closest to `target` tiles in `depth` layers, and how far off it is."""
    best = None
    for cols in range(4, 9):
        for rows in range(4, 10):
            base = tile_shape(shape, cols, rows)
            if len(base) < 6:
                continue
            layers = trim_mirrored(stack_layers(base, depth, style, random.Random(rng.random())))
            off = abs(count(layers) - target) + abs(cols - 7) + 12 * max(0, depth - len(layers))
            if best is None or off < best[0]:
                best = (off, layers)
    return best[0], normalize(best[1])


def mirrored_pairs(cells, width):
    """Left-half cells with their mirror, the middle column on its own."""
    return [c for c in sorted(cells) if 2 * c[0] <= width]


def add_marks(number, band, layers, rng):
    marks = {}
    width = max(x for layer in layers for x, _ in layer)
    top = len(layers) - 1
    chapter = (number - 1) // 10
    kinds = ["frozen", "hidden"] + (["linked"] if number >= LINKED_FROM else []) + (["spawner"] if number >= SPAWNER_FROM else [])
    wanted = {"easy": 0 if number % 2 else 1, "normal": 1 + number % 2 if number < 60 else 1, "hard": 2, "superHard": 3}[band]
    picks = rng.sample(kinds, min(len(kinds), wanted))
    if number == LINKED_FROM:
        picks = ["linked"]
    elif number == SPAWNER_FROM:
        picks = ["spawner"]

    def put(layer, cells, mark, pairs):
        free = [c for c in mirrored_pairs(cells, width) if (layer, c[0], c[1]) not in marks]
        for (x, y) in rng.sample(free, min(len(free), pairs)):
            marks[(layer, x, y)] = mark
            marks[(layer, width - x, y)] = mark

    if "frozen" in picks:
        put(0, layers[0], "F" if band in ("hard", "superHard") and number >= 25 else "f", 1 + chapter // 3)
    if "hidden" in picks and top >= 1:
        put(1 if top >= 2 else 0, layers[1 if top >= 2 else 0], "h", 2 + chapter // 3)
    if "linked" in picks:
        free = [c for c in mirrored_pairs(layers[top], width) if 2 * c[0] != width and (top, c[0], c[1]) not in marks]
        for digit, (x, y) in enumerate(rng.sample(free, min(len(free), 1 + chapter // 3)), start=1):
            marks[(top, x, y)] = str(digit)
            marks[(top, width - x, y)] = str(digit)
    if "spawner" in picks:
        # One spawner, in the middle column; a board without one goes without.
        middle = [c for c in sorted(layers[top]) if 2 * c[0] == width and (top, c[0], c[1]) not in marks]
        if middle:
            marks[(top, middle[0][0], middle[0][1])] = "s"
    return marks


def procedural(number, previous):
    rng = random.Random(4000 + number)
    band = band_at(number)
    scale = {"easy": 0.55, "normal": rng.uniform(0.85, 1.1), "hard": 1.3, "superHard": 1.45}[band]
    target = min(165, int((45 + 0.7 * number) * scale))
    kinds = min({"easy": 9, "normal": 11, "hard": 12, "superHard": 12}[band], 6 + number // 10 + {"easy": -2, "normal": 0, "hard": 1, "superHard": 1}[band])
    depth = min(6, 2 + (number - 1) // 20 + {"easy": 0, "normal": 0, "hard": 1, "superHard": 2}[band])
    # The first shape, in a shuffled order, that gets within a fifth of the target size.
    shapes = [s for s in SHAPES if s not in previous]
    rng.shuffle(shapes)
    best = None
    for shape in shapes:
        style = rng.choice(["pyramid", "brick", "brick", "stack"])
        off, layers = fit(shape, target, depth, style, rng)
        if best is None or off < best[0]:
            best = (off, layers, shape)
        if off <= target // 5:
            break
    _, layers, shape = best
    kinds = max(3, min(kinds, count(layers) // 3))
    return layers, kinds, band, shape


def main():
    os.makedirs(OUT, exist_ok=True)
    hand = {name: (kinds, build) for name, kinds, _, build in RECIPES}
    previous = []
    for number in range(1, 101):
        name = f"L{number:03d}"
        if number in HAND_ORDER:
            source = HAND_ORDER[number]
            kinds, build = hand[source]
            layers = normalize([set(c) for c in build()])
            marks = MODIFIERS.get(source, lambda _: {})(layers)
            write(name, layers, kinds, band_at(number), marks, extra=(f"# from recipe {source}",) if source != name else ())
            continue
        layers, kinds, band, shape = procedural(number, previous[-2:])
        previous.append(shape)
        marks = add_marks(number, band, layers, random.Random(5000 + number))
        write(name, layers, kinds, band, marks, extra=(f"# {shape}",))


if __name__ == "__main__":
    main()
